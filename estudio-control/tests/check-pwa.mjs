import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('public/manifest.webmanifest',root),'utf8'));
const html = readFileSync(new URL('index.html',root),'utf8');
const worker = readFileSync(new URL('public/sw.js',root),'utf8');
const main = readFileSync(new URL('src/main.tsx',root),'utf8');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.lang,'es');
assert.equal(manifest.start_url,'./');
assert.equal(manifest.scope,'./');
assert.ok(manifest.icons.some(x => x.sizes==='192x192' && x.type==='image/png'));
assert.ok(manifest.icons.some(x => x.sizes==='512x512' && x.type==='image/png'));
assert.ok(html.includes('rel="manifest"'));
assert.ok(html.includes('apple-touch-icon'));
assert.ok(html.includes('apple-mobile-web-app-capable'));
assert.ok(html.includes('viewport-fit=cover'));
assert.ok(main.includes("serviceWorker.register"));
assert.ok(worker.includes("request.mode === 'navigate'"));
assert.ok(worker.includes("request.headers.has('Authorization')"));
assert.ok(worker.includes("url.origin !== self.location.origin"));
console.log('Podcast PWA: manifest, iOS, iconos, scope y cache seguro comprobados.');
