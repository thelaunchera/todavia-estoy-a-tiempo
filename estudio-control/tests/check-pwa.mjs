import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('public/manifest.webmanifest',root),'utf8'));
const html = readFileSync(new URL('index.html',root),'utf8');
const worker = readFileSync(new URL('public/sw.js',root),'utf8');
const main = readFileSync(new URL('src/main.tsx',root),'utf8');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.lang,'es');
assert.equal(manifest.start_url,'./');
assert.equal(manifest.scope,'./');
assert.ok(manifest.icons.some(x => x.sizes==='192x192' && x.type==='image/png'));
assert.ok(manifest.icons.some(x => x.sizes==='512x512' && x.type==='image/png'));
assert.ok(html.includes('rel="manifest"'));
assert.ok(html.includes('apple-touch-icon'));
assert.ok(html.includes('apple-mobile-web-app-capable'));
assert.ok(html.includes('viewport-fit=cover'));
assert.ok(main.includes("serviceWorker.register"));
assert.ok(worker.includes("request.mode === 'navigate'"));
assert.ok(worker.includes("request.headers.has('Authorization')"));
assert.ok(worker.includes("url.origin !== self.location.origin"));
const studio = readFileSync(new URL('src/Studio.tsx',root),'utf8');
const studioCss = readFileSync(new URL('src/studio.css',root),'utf8');
assert.ok(studio.includes("{ id: 'youtube', label: 'YouTube · Nia y Ruby'"));
assert.ok(studio.includes("{ id: 'seamless', label: 'Carruseles seamless'"));
assert.ok(studio.includes("cache:'no-store'"),'studio checks Pages HTML without cached stale shell');
assert.ok(studio.includes("window.addEventListener('pageshow',onResume)"),'iPhone PWA checks when resumed');
assert.ok(studio.includes("navigator.serviceWorker?.addEventListener('controllerchange',onResume)"));
assert.ok(studio.includes("setStudioUpdateAvailable(true)"));
assert.ok(studio.includes("studio-update-notice"),'new build notice is rendered before content');
assert.ok(studioCss.includes('.studio-update-notice'));
assert.ok(studio.includes("if(unauthorized)setDenied(true)"),'only confirmed access denial hides the private studio');
assert.ok(!studio.includes("} catch {\\n      setDenied(true);"),'network failures must not look like access removal');
assert.ok(worker.includes("request.mode === 'navigate'"),'navigation keeps using online HTML to avoid stale menus');
console.log('Podcast PWA: manifest, iOS, iconos, scope y cache seguro comprobados.');
