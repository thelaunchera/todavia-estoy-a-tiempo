import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('public/manifest.webmanifest',root),'utf8'));
const html = readFileSync(new URL('index.html',root),'utf8');
const worker = readFileSync(new URL('public/sw.js',root),'utf8');
const main = readFileSync(new URL('src/main.tsx',root),'utf8');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.lang,'es');
assert.equal(manifest.start_url,'./');
assert.equal(manifest.scope,'./');
assert.ok(manifest.icons.some(x => x.sizes==='192x192' && x.type==='image/png'));
assert.ok(manifest.icons.some(x => x.sizes==='512x512' && x.type==='image/png'));
assert.ok(html.includes('rel="manifest"'));
assert.ok(html.includes('apple-touch-icon'));
assert.ok(html.includes('apple-mobile-web-app-capable'));
assert.ok(html.includes('viewport-fit=cover'));
assert.ok(main.includes("serviceWorker.register"));
assert.ok(worker.includes("request.mode === 'navigate'"));
assert.ok(worker.includes("request.headers.has('Authorization')"));
assert.ok(worker.includes("url.origin !== self.location.origin"));
const studio = readFileSync(new URL('src/Studio.tsx',root),'utf8');
const studioCss = readFileSync(new URL('src/studio.css',root),'utf8');
assert.ok(studio.includes("{ id: 'youtube', label: 'YouTube · The Launch Era'"));
const youtubeStudio = readFileSync(new URL('src/YouTubeStudio.tsx',root),'utf8');
const currentYoutubePlan = readFileSync(new URL('src/TheLaunchEraYouTubePlan.tsx',root),'utf8');
assert.ok(youtubeStudio.includes('<TheLaunchEraYouTubePlan />'), 'current animated series is first in Studio YouTube');
assert.ok(youtubeStudio.includes('<details className="yt-archive-section">'), 'legacy OFF BRIEF appears in a collapsed archive');
assert.ok(youtubeStudio.includes('Archivo · OFF BRIEF'), 'legacy project retains its archive name');
assert.ok(currentYoutubePlan.includes('The Little Detours'), 'current plan is present');
assert.ok(currentYoutubePlan.includes('The Umbrella Thief'), 'pilot remains indexed');
assert.ok(currentYoutubePlan.includes('<TheLittleDetoursFlow />'), 'Google Flow production panel is visible in active YouTube plan');
const flowPrompts = readFileSync(new URL('src/youtube/google-flow-umbrella.ts',root),'utf8');
const flowUI = readFileSync(new URL('src/TheLittleDetoursFlow.tsx',root),'utf8');
assert.equal((flowPrompts.match(/number: [1-7], title:/g)||[]).length,7,'pilot contains seven individually grounded continuous segments');
assert.ok(flowPrompts.includes('EXTEND THE PREVIOUS GENERATED VIDEO'), 'continuation uses previous video instead of scene reset');
assert.ok(flowPrompts.includes('NO hard cuts, jump cuts'), 'global negative continuity instructions are included');
assert.ok(flowUI.includes('Copiar este prompt'), 'each scene has usable copy control');


assert.ok(studio.includes("{ id: 'seamless', label: 'Carruseles seamless'"));
assert.ok(studio.includes("cache:'no-store'"),'studio checks Pages HTML without cached stale shell');
assert.ok(studio.includes("window.addEventListener('pageshow',onResume)"),'iPhone PWA checks when resumed');
assert.ok(studio.includes("navigator.serviceWorker?.addEventListener('controllerchange',onResume)"));
assert.ok(studio.includes("setStudioUpdateAvailable(true)"));
assert.ok(studio.includes("studio-update-notice"),'new build notice is rendered before content');
assert.ok(studioCss.includes('.studio-update-notice'));
const studioAuth=readFileSync(new URL('src/supabase-client.ts',root),'utf8');
assert.ok(studioAuth.includes("if(error)throw new Error('La conexión no permite verificar la sesión."),'transient auth failures are not sign-out events');
assert.ok(studioAuth.includes("if(!user)return null;"),'only missing auth user returns a logged-out state');
assert.ok(studioAuth.includes("if(roleError)throw new Error('No se pudo verificar el permiso"),'temporary role lookup errors do not revoke permissions');
assert.ok(studio.includes("if(unauthorized)setDenied(true)"),'only confirmed access denial hides the private studio');
assert.ok(!/catch\s*\{\s*setDenied\(true\)/.test(studio),'network failures must not look like access removal');
assert.ok(worker.includes("request.mode === 'navigate'"),'navigation keeps using online HTML to avoid stale menus');
console.log('Podcast PWA: manifest, iOS, iconos, scope y cache seguro comprobados.');
